#!/usr/bin/env tsx
/**
 * Bootstrap Shield (cold storage): create project + custom auth provider.
 * Idempotent: skips if web/.env.local already has SHIELD_API_KEY.
 * Run with: npx tsx scripts/bootstrap-shield.ts
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "fs";
import { join } from "path";

const SHIELD_URL = process.env["COLD_STORAGE_URL"] ?? "http://localhost:7053";
const ENV_LOCAL = join(import.meta.dirname ?? ".", "..", "web", ".env.local");

async function main() {
  if (existsSync(ENV_LOCAL)) {
    const content = readFileSync(ENV_LOCAL, "utf8");
    if (content.includes("SHIELD_API_KEY=") && !content.includes("SHIELD_API_KEY=\n")) {
      console.log("bootstrap-shield: web/.env.local already populated, skipping");
      return;
    }
  }

  // 1. Register a new Shield project
  console.log("bootstrap-shield: creating Shield project...");
  const registerRes = await fetch(`${SHIELD_URL}/register`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ name: "embedded-wallet-demo", generate_encryption_key: true }),
  });
  if (!registerRes.ok) {
    const text = await registerRes.text();
    throw new Error(`Shield register failed ${registerRes.status}: ${text}`);
  }
  const project = await registerRes.json() as {
    id: string;
    api_key: string;
    api_secret: string;
    encryption_part: string;
  };
  console.log(`bootstrap-shield: project id=${project.id}`);

  // 2. Set up custom auth provider (JWK URL uses internal docker hostname)
  console.log("bootstrap-shield: configuring custom auth provider...");
  const providerRes = await fetch(`${SHIELD_URL}/project/providers`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-API-Key": project.api_key,
      "X-API-Secret": project.api_secret,
    },
    body: JSON.stringify({
      providers: {
        custom: {
          jwk: "http://authservice:3000/.well-known/jwks.json",
        },
      },
    }),
  });
  if (!providerRes.ok) {
    const text = await providerRes.text();
    throw new Error(`Shield set-provider failed ${providerRes.status}: ${text}`);
  }
  const providerData = await providerRes.json() as unknown;
  console.log("bootstrap-shield: provider set", JSON.stringify(providerData));

  // 3. Write web/.env.local
  mkdirSync(join(import.meta.dirname ?? ".", "..", "web"), { recursive: true });
  const envContent = [
    `# Generated by scripts/bootstrap-shield.ts`,
    `SHIELD_API_KEY=${project.api_key}`,
    `SHIELD_API_SECRET=${project.api_secret}`,
    `SHIELD_ENCRYPTION_PART=${project.encryption_part}`,
    `# Public — iframe reads this client-side`,
    `NEXT_PUBLIC_SHIELD_API_KEY=${project.api_key}`,
    `# Service URLs`,
    `NEXT_PUBLIC_AUTH_URL=http://localhost:7052`,
    `NEXT_PUBLIC_HOT_STORAGE_URL=http://localhost:7054`,
    `NEXT_PUBLIC_COLD_STORAGE_URL=http://localhost:7053`,
    `NEXT_PUBLIC_IFRAME_URL=http://localhost:7050/index.html?debug=true`,
  ].join("\n") + "\n";

  writeFileSync(ENV_LOCAL, envContent, "utf8");
  console.log(`bootstrap-shield: wrote ${ENV_LOCAL}`);
  console.log("bootstrap-shield: done");
}

main().catch((err) => {
  console.error("bootstrap-shield error:", err);
  process.exit(1);
});
